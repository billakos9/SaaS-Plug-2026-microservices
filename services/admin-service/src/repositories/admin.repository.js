import Admin from "../models/admin.model.js";
import Counter from "../models/counter.model.js";


/**
 * Repository class for admin data access. Provides methods to create, read, update, and delete admin records in MongoDB. Also includes a method to generate sequential admin IDs using a counter collection.
 * All methods return plain JavaScript objects (lean) for better performance, except create which returns the Mongoose document.
 * 
 */
class AdminRepository {
  /**
   * Atomically increments and retrieves the next adminId value from the Counter collection. This ensures unique, sequential IDs for new admin records without race conditions
   * 
   * @returns {Promise<number>} The next available adminId
   * @throws {Error} If there is an issue accessing the database or updating the counter
   */
  static async getNextId() {
    const counter = await Counter.findOneAndUpdate(
      { name: "adminId" },
      { $inc: { value: 1 } },
      { new: true, upsert: true },
    );
    return counter.value;
  }
  /**
   * Retrieves all admin records from the database as plain JavaScript objects. This method is used to get a list of all admins without the overhead of Mongoose documents.
   * 
   * @returns {Promise<Array>} A list of all admin records as plain JavaScript objects
   * @throws {Error} If there is an issue accessing the database
   */
  static async getAll() {
    return Admin.find().lean();
  }

  /**
   * Retrieves an admin record by their ID from the database as a plain JavaScript object. This method is used to get the details of a specific admin without the overhead of a Mongoose document.
   * 
   * @param {number} adminId 
   * @returns {Promise<Object>} The admin record as a plain JavaScript object
   * @throws {Error} If there is an issue accessing the database or if the admin is not found
   */
  static async getById(adminId) {
    return Admin.findOne({ adminId }).lean();
  }

  /**
   * Retrieves an admin record by their email from the database as a plain JavaScript object. This method is used to get the details of a specific admin without the overhead of a Mongoose document.
   * 
   * @param {string} email 
   * @returns {Promise<Object>} The admin record as a plain JavaScript object
   * @throws {Error} If there is an issue accessing the database or if the admin is not found
   */
  static async getByEmail(email) {
    return Admin.findOne({ email }).lean();
  }

  /**
   * Creates a new admin record in the database. The adminData parameter should include all necessary fields for the admin, including a unique adminId generated by getNextId. This method returns the created Mongoose document.
   * 
   * @param {Object} adminData 
   * @returns {Promise<Object>} The created admin record as a Mongoose document
   * @throws {Error} If there is an issue accessing the database or if the admin cannot be created
   */
  static async create(adminData) {
    return Admin.create(adminData);
  }

  /**
   * Updates an existing admin record in the database. The updatedData parameter should include the adminId and any fields to be updated. This method returns the updated Mongoose document.
   * 
   * @param {Object} updatedData 
   * @returns {Promise<Object>} The updated admin record as a Mongoose document
   * @throws {Error} If there is an issue accessing the database or if the admin cannot be updated
   */
  static async update(updatedData) {
    const { adminId, ...updateData } = updatedData;
    return Admin.findOneAndUpdate({ adminId }, { $set: updateData }, { new: true }).lean();
  }

  /**
   * Deletes an admin record from the database by their ID.
   * 
   * @param {number} adminId 
   * @returns {Promise<Object>} The result of the delete operation
   * @throws {Error} If there is an issue accessing the database or if the admin cannot be deleted
   */
  static async delete(adminId) {
    return Admin.deleteOne({ adminId });
  }
}

export default AdminRepository;
